"use strict";
// Writes src/greymarch/templatePinned.ts: the objects SkyrimPlatform's start save (skyrim-platform/.../assets/template.ess, an old unmodded LE save) pins to a
// position. Every game is started from that save, and a promoted or moved REFR change form in it carries a stored position that wins over every plugin, so a
// mod that moved such an object is undone for everyone (2026-10-24: the Jorrvaskr living-quarters door 077FA2 stood at the vanilla spot inside JK's new walls).
// Each entry is [form id as the game resolves it, x, y, z] (whole units). Default ids are Skyrim.esm ids; indexed ids come from the save's formIDArray, whose top
// byte is a load-order slot: SkyrimPlatform overwrites the plugin names with ours without remapping, so that slot means OUR plugin at that place, as the game
// reads it. Run: node tools/greymarch-template-pinned.js
const fs = require("node:fs");
const path = require("node:path");

const PROMOTED = 0x2000000, MOVED = 0x2;

function readPinned(b) {
  let o = 13;
  const hs = b.readUInt32LE(o); o += 4;
  const h0 = o;
  const ver = b.readUInt32LE(h0);
  o = h0 + hs;
  let p = h0 + 8;
  const ws = () => { const n = b.readUInt16LE(p); p += 2 + n; };
  ws(); p += 4; ws(); ws(); ws(); p += 2 + 4 + 4 + 8;
  const w = b.readUInt32LE(p), h = b.readUInt32LE(p + 4);
  o += w * h * (ver >= 12 ? 4 : 3); // the screenshot: RGB in the old format, RGBA in the new
  o += 1; // form version
  const pluginInfoSize = b.readUInt32LE(o); o += 4 + pluginInfoSize;
  const table = []; for (let i = 0; i < 10; i++) { table.push(b.readUInt32LE(o)); o += 4; }
  const [formIdArrayCountOffset, , , , changeFormsOffset, , , , , changeFormCount] = table;
  const fidCount = b.readUInt32LE(formIdArrayCountOffset);
  const fid = (i) => b.readUInt32LE(formIdArrayCountOffset + 4 + 4 * i);
  const resolve = (r) => { const t = r >>> 22, v = r & 0x3fffff; if (t === 1) return v; if (t === 0) return v === 0 || v > fidCount ? null : fid(v - 1); return null; }; // 2 = made in that game: not ours
  const out = [];
  o = changeFormsOffset;
  for (let k = 0; k < changeFormCount; k++) {
    const ref = (b[o] << 16) | (b[o + 1] << 8) | b[o + 2]; o += 3;
    const flags = b.readUInt32LE(o); o += 4;
    const type = b[o]; o += 2; // type, version
    const sz = type >> 6;
    const rd = () => { let v; if (sz === 0) { v = b[o]; o += 1; } else if (sz === 1) { v = b.readUInt16LE(o); o += 2; } else { v = b.readUInt32LE(o); o += 4; } return v; };
    const len1 = rd(), len2 = rd();
    const d = b.subarray(o, o + len1); o += len1;
    if ((type & 0x3f) !== 0 || !(flags & (PROMOTED | MOVED)) || len2 > 0 || len1 < 15) continue; // REFRs with a stored position, uncompressed
    const id = resolve(ref);
    if (id === null || id === undefined) continue;
    const r = (v) => Math.round(v) || 0; // never -0
    out.push([id >>> 0, r(d.readFloatLE(3)), r(d.readFloatLE(7)), r(d.readFloatLE(11))]);
  }
  return out;
}

if (require.main === module) {
  const root = path.join(__dirname, "..", "..");
  const ess = path.join(root, "skyrim-platform", "src", "platform_se", "skyrim_platform", "assets", "template.ess");
  const list = readPinned(fs.readFileSync(ess));
  const flat = [].concat(...list);
  const text = "// GENERATED by tools/greymarch-template-pinned.js from skyrim-platform/.../assets/template.ess: do not edit by hand.\n" +
    "// [form id, x, y, z] x " + list.length + ": the objects SkyrimPlatform's start save pins to a position (see templateFix.ts).\n" +
    "export const TEMPLATE_PINNED: number[] = [" + flat.join(",") + "];\n";
  fs.writeFileSync(path.join(root, "skymp5-client", "src", "greymarch", "templatePinned.ts"), text);
  console.log(`${list.length} pinned objects written`);
}

module.exports = { readPinned };
